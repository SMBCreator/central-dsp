-- 024_creative_kktu.sql
-- ККТУ-классификатор на уровне креатива (маркировка объявлений, 38-ФЗ «О рекламе»).
--
-- Как на Авито: код ККТУ выбирается на шаге «Маркировка» для каждого креатива и
-- уходит в ОРД вместе с регистрацией. Кампания сохраняет kktu_code/kktu_label
-- (миграция 014) как значение по умолчанию — оно НЕ удаляется и используется как
-- запасной вариант, если у креатива классификатор не задан.
--
-- Аддитивная миграция: существующие данные не меняются.

ALTER TABLE creatives ADD COLUMN IF NOT EXISTS kktu_code  TEXT;
ALTER TABLE creatives ADD COLUMN IF NOT EXISTS kktu_label TEXT;

COMMENT ON COLUMN creatives.kktu_code  IS 'Код категории ККТУ (например, 1.1.1), маркировка объявления для ОРД';
COMMENT ON COLUMN creatives.kktu_label IS 'Человекочитаемая категория ККТУ (полный путь), денормализовано для отчётов';
